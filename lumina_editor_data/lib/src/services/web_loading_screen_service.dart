  /// The loading screen's script. [LuminaWebLoading.rendererStart] and
  /// [LuminaWebLoading.rendererEnd] are the phase boundaries the generated
  /// `main()` reports against.
  static String loadingJs(ResolvedWebLoadingStyle style, {bool preview = false}) {
    const engine = LuminaWebLoading.engineEnd;
    const start = LuminaWebLoading.rendererStart;
    const end = LuminaWebLoading.rendererEnd;
    return '''/* $generatedNotice */
(function () {
  'use strict';
  var FADE_MS = ${style.fadeMs};
  // The share of the bar each loading phase fills. The engine phase is
  // tracked here; the generated main() reports the renderer and the asset
  // preload through window.luminaLoading.progress (LuminaWebLoading).
  var PHASES = { engine: [0, $engine], renderer: [$start, $end], assets: [$end, 1] };

  var root = document.getElementById('lumina-loading');
  var shown = 0;
  var label = 'Loading…';
  var suffix = '';
  var hidden = false;

  function find(cls) { return root ? root.querySelector('.' + cls) : null; }

  function render() {
    if (!root) return;
    var pct = Math.round(shown * 100);
    var fill = find('lumina-loading-bar-fill');
    if (fill) fill.style.width = (shown * 100).toFixed(1) + '%';
    var ring = find('lumina-loading-ring-fill');
    if (ring) ring.style.strokeDashoffset = String(100 - shown * 100);
    var percents = root.querySelectorAll('.lumina-loading-percent');
    for (var i = 0; i < percents.length; i++) percents[i].textContent = pct + '%';
    var text = find('lumina-loading-label');
    if (text) text.textContent = label + suffix;
    root.setAttribute('aria-valuenow', String(pct));
  }

  // Moves the screen to [fraction] (0-1); it never goes backwards.
  function progress(fraction, text) {
    if (hidden) return;
    var f = Math.max(0, Math.min(1, Number(fraction) || 0));
    if (f > shown) shown = f;
    if (text) {
      label = String(text);
      suffix = '';
    }
    render();
  }

  function phase(name, fraction, text) {
    var range = PHASES[name];
    progress(range[0] + (range[1] - range[0]) * Math.max(0, Math.min(1, fraction)), text);
  }

  function fail(message) {
    if (root) root.classList.add('lumina-error');
    label = 'Could not start: ' + message;
    render();
  }

  function hide() {
    if (hidden || !root) return;
    progress(1);
    hidden = true;
    root.classList.add('lumina-done');
    setTimeout(function () {
      if (root && root.parentNode) root.parentNode.removeChild(root);
    }, FADE_MS + 50);
  }

  function mb(bytes) { return (bytes / 1048576).toFixed(1) + ' MB'; }

  // --- download tracking: the real bytes of every engine and renderer file.
  var downloads = {};
  var entrypointDone = false;

  function phaseOf(url) {
    if (/flutter_filament\\.wasm(\\?|\$)/.test(url)) return 'renderer';
    if (/\\/assets\\/contents\\//.test(url)) return 'assets';
    if (/(canvaskit|skwasm|skwasm_heavy|skwasm_st)\\.wasm(\\?|\$)/.test(url) || /main\\.dart\\.(wasm|mjs)(\\?|\$)/.test(url)) return 'engine';
    return null;
  }

  function update(name) {
    var loaded = 0, total = 0, unknown = false;
    for (var url in downloads) {
      var d = downloads[url];
      if (d.phase !== name) continue;
      loaded += d.loaded;
      if (d.total > 0) total += Math.max(d.total, d.loaded); else unknown = true;
      if (d.done && d.total <= 0) total += d.loaded;
    }
    var bytes = total > 0 ? Math.min(1, loaded / total) : 0;
    if (name === 'engine') {
      // The Dart entrypoint (main.dart.js) arrives through a script tag, so
      // it counts once it has loaded; the renderer module streams through fetch.
      var fraction = (entrypointDone ? 0.5 : 0) + 0.5 * bytes;
      phase('engine', fraction, 'Downloading the engine' + (total > 0 && !unknown ? ' (' + mb(loaded) + ' / ' + mb(total) + ')' : ''));
    } else if (name === 'renderer') {
      phase('renderer', bytes, 'Downloading the renderer' + (total > 0 ? ' (' + mb(loaded) + ' / ' + mb(total) + ')' : ''));
    } else if (name === 'assets' && shown < 1) {
      // The preload's count comes from main(); the bytes streaming in go under it.
      suffix = ' · ' + mb(loaded);
      render();
    }
  }

  var nativeFetch = window.fetch;
  if (nativeFetch && window.ReadableStream && window.Response) {
    window.fetch = function (input, init) {
      return nativeFetch.apply(this, arguments).then(function (response) {
        var url = response.url || (typeof input === 'string' ? input : (input && input.url) || '');
        var name = phaseOf(url);
        if (!name || !response.ok || !response.body || hidden) return response;
        var d = downloads[url] = { phase: name, loaded: 0, total: Number(response.headers.get('content-length')) || 0, done: false };
        var reader = response.body.getReader();
        var counted = new ReadableStream({
          pull: function (controller) {
            return reader.read().then(function (chunk) {
              if (chunk.done) {
                d.done = true;
                update(name);
                controller.close();
                return;
              }
              d.loaded += chunk.value.byteLength;
              update(name);
              controller.enqueue(chunk.value);
            });
          },
          cancel: function (reason) { return reader.cancel(reason); }
        });
        var wrapped = new Response(counted, { status: response.status, statusText: response.statusText, headers: response.headers });
        try { Object.defineProperty(wrapped, 'url', { value: response.url }); } catch (e) { /* url stays empty */ }
        return wrapped;
      });
    };
  }

  if (window.PerformanceObserver) {
    try {
      new PerformanceObserver(function (list) {
        list.getEntries().forEach(function (entry) {
          if (!entrypointDone && /main\\.dart\\.js(\\?|\$)/.test(entry.name)) {
            entrypointDone = true;
            update('engine');
          }
        });
      }).observe({ type: 'resource', buffered: true });
    } catch (e) { /* older browsers: the entrypoint counts when it starts */ }
  }

  // --- the Flutter loader (flutter_bootstrap.js hands it over before load()).
  function attach(loader) {
    if (!loader || loader.__luminaAttached) return;
    loader.__luminaAttached = true;
    var load = loader.load.bind(loader);
    loader.load = function (options) {
      options = options || {};
      var onEntrypointLoaded = options.onEntrypointLoaded;
      progress(0.01, 'Downloading the engine');
      var patched = {};
      for (var key in options) patched[key] = options[key];
      patched.onEntrypointLoaded = function (engineInitializer) {
        entrypointDone = true;
        update('engine');
        progress(shown, 'Starting the engine');
        if (onEntrypointLoaded) return onEntrypointLoaded(engineInitializer);
        return engineInitializer.initializeEngine().then(function (appRunner) {
          phase('engine', 1, 'Starting the game');
          return appRunner.runApp();
        });
      };
      var started = load(patched);
      if (started && started.catch) started.catch(function (e) { fail(e && e.message ? e.message : String(e)); });
      return started;
    };
  }

  window.addEventListener('flutter-first-frame', hide);

  window.luminaLoading = {
    progress: progress,
    attach: attach,
    hide: hide,
    phases: PHASES,
    get fraction() { return shown; },
    get label() { return label; },
    get hidden() { return hidden; }
  };
  render();
${preview ? _previewDemo : ''}})();
''';
  }

  /// The browser preview (no Flutter app): walks through the real labels.
  static const String _previewDemo = '''
  // Preview: a demo of the phases, looping, without a game behind it.
  (function demo() {
    var steps = [[0.25, 'Downloading the engine'], [0.55, 'Starting the engine'], [0.72, 'Downloading the renderer'],
      [0.85, 'Loading game assets'], [1, 'Starting the game']];
    var t = 0;
    var timer = setInterval(function () {
      t += 0.01;
      var text = steps[0][1];
      for (var i = 0; i < steps.length; i++) { if (t <= steps[i][0]) { text = steps[i][1]; break; } }
      progress(Math.min(t, 1), text);
      if (t >= 1.3) {
        clearInterval(timer);
        shown = 0;
        demo();
      }
    }, 40);
  })();
''';

  /// The `web/flutter_bootstrap.js` template: Flutter substitutes its loader
  /// and build config at build time; the loading screen is attached to the
  /// loader before it starts.
  static String flutterBootstrapJs() => '''
// $generatedNotice
{{flutter_js}}
{{flutter_build_config}}

if (window.luminaLoading) window.luminaLoading.attach(_flutter.loader);
_flutter.loader.load();
''';
}
