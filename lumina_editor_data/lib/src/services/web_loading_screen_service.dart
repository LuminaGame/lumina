          <circle class="lumina-loading-ring-fill" cx="50" cy="50" r="44" pathLength="100"></circle>
        </svg>
        <div class="lumina-loading-percent lumina-loading-ring-percent">0%</div>
      </div>''',
      'percentage' => '''
      <div class="lumina-loading-percent lumina-loading-percent-large">0%</div>''',
      _ => '''
      <div class="lumina-loading-bar"><div class="lumina-loading-bar-fill"></div></div>''',
    };
    return '''<!DOCTYPE html>
<!-- $generatedNotice -->
<html lang="en"${preview ? ' data-lumina-preview' : ''}>
<head>
  <base href="\$FLUTTER_BASE_HREF">
