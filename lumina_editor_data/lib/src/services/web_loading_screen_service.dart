import 'dart:io';
import 'dart:typed_data';

import 'package:lumina/lumina.dart';

/// What [WebLoadingScreenService.write] did.
class WebLoadingScreenReport {
  /// Written files, relative to the project (or to the preview folder).
  final List<String> files;

  /// The logo's file name next to `index.html`, or null (no logo).
  final String? logoFile;

  /// Why the logo could not be used, and similar non-fatal notes.
  final List<String> warnings;

  /// Set when nothing was written (the project has no `web/` platform folder).
  final String? skippedReason;

  const WebLoadingScreenReport({this.files = const [], this.logoFile, this.warnings = const [], this.skippedReason});

  bool get written => skippedReason == null;
}

/// Generates a web build's loading screen from the project's
/// [ProjectWebLoadingStyle]: `web/index.html`, `web/loading.css`,
/// `web/loading.js`, `web/flutter_bootstrap.js` and the logo.
///
/// The page is plain HTML/CSS/JS with nothing from another origin (no fonts,
/// no CDN): it shows from the first byte, before any Flutter code arrives.
/// - `loading.js` wraps `window.fetch` to count the bytes of the engine's
///   wasm and of flutter_filament's module as they stream in, and wraps
///   `_flutter.loader.load` (called from the generated `flutter_bootstrap.js`
///   template, which Flutter fills in at build time) to follow the engine's
///   start;
/// - it exposes `window.luminaLoading.progress(fraction, label)`, which the
///   generated `main()` calls through [LuminaWebLoading] for the renderer and
///   the asset preload;
/// - it fades the screen out on Flutter's `flutter-first-frame` event.
///
/// Packaging (Package Project, Cook & Package) writes these files into the
/// project's `web/` before `flutter build web`; `index.html` is regenerated
/// every time, so edits go in Project Settings, not in the file.
abstract final class WebLoadingScreenService {
  static const String generatedNotice =
      'Generated by Lumina from Project Settings > Packaging & Target > Web Loading Style. Edits here are overwritten when the game is packaged.';

  static const String logoBaseName = 'loading_logo';

  /// Writes the loading screen into `<projectDir>/web` (or [outDir]).
  ///
  /// The logo: [ProjectWebLoadingStyle.logoFromIcon] uses [iconPng] (the
  /// editor's rasterized project icon) when given, else the project icon
  /// file, else the web app icon (`web/icons/Icon-512.png`, which packaging
  /// writes from the project icon). A project-relative image is copied.
  ///
  /// [preview] writes a page for a browser preview: no Flutter bootstrap,
  /// and `loading.js` plays a demo progress instead.
  static WebLoadingScreenReport write({
    required String projectDir,
    required LuminaProject project,
    Uint8List? iconPng,
    String? outDir,
    bool preview = false,
  }) {
    final webDir = Directory('$projectDir/web');
    if (outDir == null && !webDir.existsSync()) {
      return WebLoadingScreenReport(
        skippedReason: '${webDir.path} does not exist, so the project has no web platform '
            '(add it with `flutter create --platforms=web .`)',
      );
    }
    final out = Directory(outDir ?? webDir.path)..createSync(recursive: true);
    final rel = outDir == null ? 'web/' : '';
    final style = project.packaging.webLoadingStyle.resolve(project);
    final warnings = <String>[];
    final files = <String>[];

    final logo = _logoSource(projectDir, project, style, iconPng, warnings);
    for (final old in out.listSync().whereType<File>()) {
      final name = old.uri.pathSegments.last;
      if (name.startsWith('$logoBaseName.') && (logo == null || name != '$logoBaseName.${logo.$1}')) old.deleteSync();
    }
    String? logoFile;
    if (logo != null) {
      logoFile = '$logoBaseName.${logo.$1}';
      File('${out.path}/$logoFile').writeAsBytesSync(logo.$2);
    }

    void put(String name, String content) {
      File('${out.path}/$name').writeAsStringSync(content);
      files.add('$rel$name');
    }

    put('index.html', indexHtml(style, logoFile: logoFile, preview: preview, description: project.description));
    put('loading.css', loadingCss(style));
    put('loading.js', loadingJs(style, preview: preview));
    if (!preview) put('flutter_bootstrap.js', flutterBootstrapJs());
    if (logoFile != null) files.add('$rel$logoFile');
    return WebLoadingScreenReport(files: files, logoFile: logoFile, warnings: warnings);
  }

  /// (extension, bytes) of the logo, or null.
  static (String, Uint8List)? _logoSource(
    String projectDir,
    LuminaProject project,
    ResolvedWebLoadingStyle style,
    Uint8List? iconPng,
    List<String> warnings,
  ) {
    if (style.logo == ProjectWebLoadingStyle.logoNone) return null;
    (String, Uint8List)? fromFile(String path, String what) {
      final file = File(path.startsWith('/') ? path : '$projectDir/$path');
      final ext = path.split('.').last.toLowerCase();
      if (!ProjectWebLoadingStyle.logoExtensions.contains(ext)) {
        warnings.add('The $what $path is not an image a browser shows (${ProjectWebLoadingStyle.logoExtensions.join(', ')}); the loading screen has no logo');
        return null;
      }
      if (!file.existsSync()) {
        warnings.add('The $what $path does not exist; the loading screen has no logo');
        return null;
      }
      return (ext == 'jpeg' ? 'jpg' : ext, file.readAsBytesSync());
    }

    if (style.logo != ProjectWebLoadingStyle.logoFromIcon) return fromFile(style.logo, 'web loading logo');
    if (iconPng != null) return ('png', iconPng);
    if (!project.branding.usesDefaultIcon) return fromFile(project.branding.icon, 'project icon');
    final appIcon = File('$projectDir/web/icons/Icon-512.png');
    if (appIcon.existsSync()) return ('png', appIcon.readAsBytesSync());
    warnings.add('No project icon image was found for the loading screen (web/icons/Icon-512.png is missing)');
    return null;
  }

  static String _html(String s) => s
      .replaceAll('&', '&amp;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;')
      .replaceAll('"', '&quot;')
      .replaceAll("'", '&#39;');

  /// The page: the loading screen's markup over the Flutter app.
