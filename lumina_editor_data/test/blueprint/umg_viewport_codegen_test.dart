import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:lumina_editor_data/lumina_editor.dart';
import 'package:vector_math/vector_math_64.dart';

import '../../../lumina/test/blueprint/generated/widget_script/wbp_customizer.g.dart';
import '../../../lumina/test/blueprint/umg_viewport_customizer_fixture.dart';

/// A character customisation screen's Viewport graph compiles into
/// `WbpCustomizerGraph` (committed as
/// `generated/widget_script/wbp_customizer.g.dart`) and edits the Viewport's
/// scene description exactly as the VM does: Construct adds the mannequin,
/// plays its idle and attaches a hat at `head`; Next Hat swaps the hat
/// mesh; Colour sets a material parameter; On Picked and On Camera Changed
/// receive the Viewport's event outputs. Regenerate after an intentional
/// generator change with
/// `UPDATE_GOLDENS=1 flutter test test/blueprint/umg_viewport_codegen_test.dart`.
const String _golden = '../lumina/test/blueprint/generated/widget_script/wbp_customizer.g.dart';

String _goldenFileOf(BlueprintGenerationResult result) {
  final b = StringBuffer()
    ..writeln('// GENERATED by test/blueprint/umg_viewport_codegen_test.dart: WBP_Customizer\'s graph script,')
    ..writeln('// as a widget file embeds it. UPDATE_GOLDENS=1 rewrites it.')
    ..writeln('// ignore_for_file: camel_case_types, non_constant_identifier_names, unused_import, prefer_const_constructors, '
        'unnecessary_this, dead_code, unused_local_variable, dead_null_aware_expression, library_prefixes')
    ..writeln()
    ..writeln("import 'package:lumina/lumina_runtime.dart';")
    ..writeln("import 'package:vector_math/vector_math_64.dart';");
  for (final i in result.imports) {
    b.writeln(i);
  }
  b
    ..writeln()
    ..write(result.code);
  return b.toString();
}

void main() {
  setUp(() => LuminaWidgetClassRegistry.register(customizerWidgetClass));
  tearDown(() {
    LuminaUserWidgets.clear();
    LuminaWidgetClassRegistry.clear();
  });

  test('the customizer graph validates in a Widget Blueprint', () {
    final doc = customizerBlueprint();
    final context = LuminaBlueprintTypeContext.forWidget(doc, widgetClasses: const [customizerWidgetClass]);
    final errors = validateBlueprint(doc.blueprint, typeContext: context).where((d) => d.isError).map((d) => '$d');
    expect(errors, isEmpty);
  });

  test('generateWidgetScript writes WbpCustomizerGraph calling the Viewport nodes', () {
    final result = const BlueprintDartGenerator().generateWidgetScript(customizerBlueprint(), className: 'WbpCustomizerGraph');
    expect(result.errors, isEmpty);
    final code = result.code!;
    expect(code, contains('.LuminaViewportNodes.addSkeletalMesh(this, '));
    expect(code, contains('.LuminaViewportNodes.attachToSocket(this, '));
    expect(code, contains('.LuminaViewportNodes.setNodeMesh(this, '));
    expect(code, contains('.LuminaViewportNodes.setMaterialParameter(this, '));
    expect(code, contains("case ('Preview', 'OnPicked'):"));
    expect(code, contains("case ('Preview', 'OnCameraChanged'):"));

    final generated = _goldenFileOf(result);
    final golden = File(_golden);
    if (Platform.environment['UPDATE_GOLDENS'] == '1') {
      golden
        ..parent.createSync(recursive: true)
        ..writeAsStringSync(generated);
    }
    expect(golden.existsSync(), isTrue, reason: 'run with UPDATE_GOLDENS=1 to create $_golden');
    expect(generated, golden.readAsStringSync(), reason: '$_golden changed; UPDATE_GOLDENS=1 regenerates it');
  });

  test('the generated WbpCustomizerGraph and the VM agree, event for event', () {
    List<String> run(LuminaUserWidget Function() factory) {
      LuminaUserWidgets.register(customizerClass, factory);
      final world = LuminaWorld(worldType: LuminaWorldType.game);
      world.beginPlay();
      final owner = world.spawnActorImmediately(LuminaActor());
      final widget = LuminaBlueprintFunctionLibrary.createWidget(owner, customizerClass) as Map<String, Object?>;
      final script = LuminaUserWidgets.of(widget)! as LuminaBlueprintRuntime;
      final steps = <String>[];
      script.trace = (e) => steps.add('${e.eventNodeId}/${e.nodeId}/${e.registryId}${e.printed == null ? '' : ' "${e.printed}"'}');
      Map<String, Object?> element(String name) => (widget['elements']! as Map)[name] as Map<String, Object?>;
      String scene() => LuminaViewportScene.of(element('Preview')).encode();

      LuminaBlueprintFunctionLibrary.addToViewport(owner, widget, 0);
      steps.add(scene());
      LuminaUserWidgets.fire(widget, 'NextHat', LuminaWidgetEvents.onClicked);
      steps.add(scene());
      LuminaUserWidgets.fire(widget, 'NextHat', LuminaWidgetEvents.onClicked);
      LuminaUserWidgets.fire(widget, 'Colour', LuminaWidgetEvents.onClicked);
      steps.add(scene());
      LuminaUserWidgets.fire(widget, 'Preview', LuminaWidgetEvents.onPicked,
          {'node_id': 'skeletal_1', 'bone': 'head', 'hit_location': Vector3(0.0, 0.0, 170.0)});
      LuminaUserWidgets.fire(widget, 'Preview', LuminaWidgetEvents.onCameraChanged, {'yaw': 45.0, 'pitch': 10.0, 'distance': 300.0});
      steps.add('status=${element('Status')['text']}');
      LuminaUserWidgets.clear();
      return steps;
    }

    final cls = LuminaBlueprintClass.forWidget(customizerBlueprint());
    final vm = run(cls.instantiateUserWidget);
    final generated = run(WbpCustomizerGraph.new);
    expect(generated, vm);

    final built = LuminaViewportScene.decode(vm.firstWhere((s) => s.startsWith('{')));
    final hero = built.nodes.firstWhere((n) => n['kind'] == LuminaViewportNodeKind.skeletalMesh);
    final hat = built.nodes.firstWhere((n) => n['kind'] == LuminaViewportNodeKind.staticMesh);
    expect(hero['asset'], customizerMannequin);
    expect((hero['animation']! as Map)['asset'], customizerIdle);
    expect((hero['animation']! as Map)['loop'], isTrue);
    expect(hat['asset'], customizerHatA);
    expect(hat['parent'], hero['id']);
    expect(hat['socket'], 'head');
    expect(built.skeletonOverlay(hero['id']! as String), isNotNull);
    expect(vm.where((s) => s.endsWith('"ready skeletal_1 mesh_2"')), hasLength(1));

    final swapped = LuminaViewportScene.decode(vm.where((s) => s.startsWith('{')).elementAt(1));
    expect(swapped.node('mesh_2')!['asset'], customizerHatB, reason: 'Next Hat swapped the hat');
    expect(LuminaViewportSceneDiff.diff(built, swapped).map((o) => '${o.kind.name} ${o.fields}'), ['updateNode {asset}']);

    final tinted = LuminaViewportScene.decode(vm.where((s) => s.startsWith('{')).elementAt(2));
    expect(tinted.node('mesh_2')!['asset'], customizerHatA, reason: 'a second Next Hat wraps around');
    expect((tinted.node('skeletal_1')!['materialParams']! as Map)['0'], {
      'baseColorFactor': [0.9, 0.2, 0.1, 1.0],
    });
    expect(vm.where((s) => s.endsWith('"picked skeletal_1 head"')), hasLength(1));
    expect(vm.last, 'status=45.00');
  });
}
