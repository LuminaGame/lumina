  });

  // The engine's versions, not pub.dev's newest: a temp engine whose lock
  // pins yaml 3.1.3 while 3.1.4 is published.
  group('the host resolves the engine lock', () {
    late Directory temp;
    late String engine;
    late String projectDir;
    late String host;

    String lockPinning(String version, String sha256, {String extra = ''}) => '''
# Generated by pub
packages:
$extra  yaml:
    dependency: transitive
    description:
      name: yaml
      sha256: "$sha256"
      url: "https://pub.dev"
    source: hosted
    version: "$version"
sdks:
  dart: ">=3.12.0 <4.0.0"
''';
    const old = ('3.1.3', 'b9da305ac7c39faa3f030eccd175340f968459dae4af175130b3fc47e40d76ce');
    const newer = ('3.1.4', 'f67cdd8e07d3c6329146aaef1ba043542b3134c12489f553ca9a7435d1068aea');

    String? lockedVersion(String lockPath, String name) {
      final yaml = loadYaml(File(lockPath).readAsStringSync()) as YamlMap;
      final entry = (yaml['packages'] as YamlMap?)?[name];
      return entry is YamlMap ? '${entry['version']}' : null;
    }

    setUp(() {
      temp = Directory.systemTemp.createTempSync('host_lock_');
      engine = p.join(temp.path, 'engine');
      File(p.join(engine, 'lumina_ui', 'pubspec.yaml'))
        ..createSync(recursive: true)
        ..writeAsStringSync('''
name: lumina_ui
publish_to: none
environment:
  sdk: ^3.12.0
dependencies:
  flutter:
    sdk: flutter
  yaml: ^3.1.0
''');
      Directory(p.join(engine, 'lumina_ui', 'lib')).createSync();
      Directory(p.join(engine, 'filament')).createSync();
      File(p.join(engine, 'pubspec.lock')).writeAsStringSync(lockPinning(old.$1, old.$2));
      projectDir = p.join(temp.path, 'Game');
      Directory(projectDir).createSync();
      host = EditorHostGeneratorService.hostDirOf(projectDir);
    });
    tearDown(() {
      try {
        temp.deleteSync(recursive: true);
      } on FileSystemException {
        // A Windows handle still open; the system temp folder keeps it.
      }
    });

    test('flutter pub get in a fresh host keeps the version the engine lock pins', () async {
      await EditorSourceVendorService(engineRoot: engine).vendor(host);
      await EditorHostGeneratorService(engineRoot: engine, platform: 'linux').generate(projectDir, const []);
      final flutter = Platform.isWindows ? 'flutter.bat' : 'flutter';
      ProcessResult get;
      try {
        get = await Process.run(flutter, ['pub', 'get', '--offline'], workingDirectory: host, runInShell: Platform.isWindows);
      } on ProcessException {
        markTestSkipped('flutter is not on PATH');
        return;
      }
      if (get.exitCode != 0) {
        get = await Process.run(flutter, ['pub', 'get'], workingDirectory: host, runInShell: Platform.isWindows);
      }
      expect(get.exitCode, 0, reason: '${get.stdout}\n${get.stderr}');
      expect(lockedVersion(p.join(host, 'pubspec.lock'), 'yaml'), old.$1, reason: 'not the newest yaml (${newer.$1})');
      expect(EditorHostGeneratorService(engineRoot: engine).movedFromEngineLock(host), isEmpty);
    }, timeout: const Timeout(Duration(minutes: 3)));

    test("the project's copy keeps the lock it was copied with; a sync takes the engine's new one", () async {
      await EditorSourceVendorService(engineRoot: engine).vendor(host);
      File(p.join(engine, 'pubspec.lock')).writeAsStringSync(lockPinning(newer.$1, newer.$2));
      final gen = EditorHostGeneratorService(engineRoot: engine, platform: 'linux');
      await gen.generate(projectDir, const []);
      expect(lockedVersion(p.join(host, 'pubspec.lock'), 'yaml'), old.$1, reason: 'the copied source was built with ${old.$1}');

      await EditorSourceVendorService(engineRoot: engine).sync(host);
      await gen.generate(projectDir, const []);
      expect(lockedVersion(p.join(host, 'pubspec.lock'), 'yaml'), newer.$1);
    });

    test('a host lock that moved an engine package is put back; packages only the host has stay', () async {
      await EditorSourceVendorService(engineRoot: engine).vendor(host);
      final gen = EditorHostGeneratorService(engineRoot: engine, platform: 'linux');
      await gen.generate(projectDir, const []);
      // What a resolution against pub.dev left behind: the newest yaml, and
      // a package only a code plugin brought.
      File(p.join(host, 'pubspec.lock')).writeAsStringSync(lockPinning(newer.$1, newer.$2, extra: '''
  args:
    dependency: transitive
    description:
      name: args
      sha256: "d0481093c50b1da8910eb0bb301626d4d8eb7284aa739614d2b394ee09e3ea04"
      url: "https://pub.dev"
    source: hosted
    version: "2.7.0"
'''));
      expect(gen.movedFromEngineLock(host), ['yaml ${old.$1} → ${newer.$1}']);

      final r = await gen.generate(projectDir, const []);
      expect(r.changed, isTrue);
      final lock = p.join(host, 'pubspec.lock');
      expect(lockedVersion(lock, 'yaml'), old.$1);
      expect(lockedVersion(lock, 'args'), '2.7.0');
      expect(gen.movedFromEngineLock(host), isEmpty);
      final bytes = File(lock).readAsBytesSync();
      expect((await gen.generate(projectDir, const [])).changed, isFalse);
      expect(File(lock).readAsBytesSync(), bytes, reason: 'an unchanged host keeps its lock');
    });
  });
