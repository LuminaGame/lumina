      ..writeAsStringSync('set(BINARY_NAME "lumina_ui") # from the copy\n');
    await EditorHostGeneratorService(engineRoot: engineRoot, platform: 'linux').generate(fx.projectDir.path, const []);
    expect(File(p.join(host, 'linux', 'CMakeLists.txt')).readAsStringSync(), 'set(BINARY_NAME "host_game_editor") # from the copy\n');
  });

  test('the generated host analyzes with 0 errors', () async {
    // An isolated plugin: the registrar's kPluginProcesses names its process
    // part and the main passes it to runLuminaEditor.
    await fx.isolate();
    final gen = EditorHostGeneratorService(engineRoot: engineRoot);
    await gen.generate(fx.projectDir.path, [await fx.plugin()]);
    final registrar = File(p.join(fx.projectDir.path, '.lumina', 'editor', 'lib', 'plugin_registrar.dart')).readAsStringSync();
    expect(registrar, contains("  'a_plugin': () => a_plugin_plugin.AProcess(),\n"));
    final host = p.join(fx.projectDir.path, '.lumina', 'editor');
    // The copy's layout, as links into the engine (copying ~650 MB is the
    // build pipeline's job, covered by editor_source_vendor_service_test).
    final sources = EditorSourceVendorService(engineRoot: engineRoot).packageSources();
    for (final rel in [...EditorSourceVendorService(engineRoot: engineRoot).copyRoots(), 'filament']) {
      final link = Link(p.join(host, rel));
      link.parent.createSync(recursive: true);
      link.createSync(sources[rel] ?? p.join(engineRoot, rel));
    }
    final flutter = Platform.isWindows ? 'flutter.bat' : 'flutter';
    ProcessResult get;
    try {
      get = await Process.run(flutter, ['pub', 'get', '--offline'], workingDirectory: host, runInShell: Platform.isWindows);
    } on ProcessException {
      markTestSkipped('flutter is not on PATH');
      return;
    }
    if (get.exitCode != 0) {
      get = await Process.run(flutter, ['pub', 'get'], workingDirectory: host, runInShell: Platform.isWindows);
    }
    expect(get.exitCode, 0, reason: '${get.stdout}\n${get.stderr}');
    final analyze = await Process.run(Platform.isWindows ? 'dart.bat' : 'dart', ['analyze', '--no-fatal-warnings', 'lib'],
        workingDirectory: host, runInShell: Platform.isWindows);
    expect(analyze.exitCode, 0, reason: '${analyze.stdout}\n${analyze.stderr}');
  }, timeout: const Timeout(Duration(minutes: 5)));

