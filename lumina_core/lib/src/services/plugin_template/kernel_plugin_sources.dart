/// The files the plugin template generator writes for a **kernel plugin**:
/// a shell-less isolated plugin whose process ships as a Dart kernel and
/// runs on the Dart VM, so enabling or disabling it needs no project editor
/// build. Pure Dart: no Flutter in its pubspec or anything its entry
/// imports.
abstract final class KernelPluginSources {
  /// [s] as the body of a single-quoted Dart string literal.
  static String _lit(String s) => s
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');

  /// `bin/<name>_process.dart`, the manifest's `process_entry`.
  static String entryPath(String pluginName) => 'bin/${pluginName}_process.dart';

  /// `pubspec.yaml`: the process API from the engine repository (git, at
  /// [engineRef] when a release editor knows it), lints and test.
  static String pubspec({
    required String pluginName,
    required String description,
    required String engineRepo,
    String? engineRef,
  }) =>
      '''
name: $pluginName
description: "${description.replaceAll('"', r'\"')}"
version: 0.1.0
publish_to: none

environment:
  sdk: ^3.12.0

# Pure Dart: the process runs on the Dart VM from a kernel file.
dependencies:
  lumina_plugin_process:
    git:
      url: $engineRepo
      path: lumina_plugin_process${engineRef == null ? '' : '\n      ref: $engineRef'}

dev_dependencies:
  lints: ^6.0.0
  test: ^1.24.0
''';

  static const String analysisOptions = '''
include: package:lints/recommended.yaml

linter:
  rules:
    - always_use_package_imports
''';

  /// `lib/<name>.dart`.
  static String library(String pluginName) => '''// GENERATED BY LUMINA PLUGIN WIZARD
library;

export 'package:$pluginName/src/${pluginName}_process.dart';
''';

  /// `bin/<name>_process.dart`: the whole `main`.
  static String entry({required String pluginName, required String pascalName}) => '''// GENERATED BY LUMINA PLUGIN WIZARD
// The kernel plugin's process entry: the editor runs it on the Dart VM
// (`dart <kernel> <launch flags>`). Pure Dart: never import Flutter here.
import 'package:lumina_plugin_process/lumina_plugin_process.dart';
import 'package:$pluginName/$pluginName.dart';

Future<void> main(List<String> args) => runPluginProcessEntry(args, ${pascalName}Process.new);
''';

  /// `lib/src/<name>_process.dart`: a menu command that asks a confirm
  /// dialog, a declarative panel and an MCP tool.
  static String processSource({
    required String pluginName,
    required String pascalName,
    required String friendlyName,
  }) {
    final friendly = _lit(friendlyName);
    return '''// GENERATED BY LUMINA PLUGIN WIZARD
import 'package:lumina_plugin_process/lumina_plugin_process.dart';

/// $friendlyName: everything it contributes is data the editor renders,
/// so it needs no code inside the editor.
class ${pascalName}Process extends LuminaPluginProcess {
  int greetings = 0;

  @override
  String get pluginName => '$pluginName';

  @override
  void register(PluginProcessContext context) {
    Future<void> greet() async {
      final ok = await context.confirm('$friendly', 'Say hello in the Output Log?', confirmLabel: 'Say hello');
      if (!ok) return;
      greetings++;
      context.log('Hello from $friendly (\$greetings)');
      context.view('$pluginName.view')?.patch(PluginViewPatch([
        PluginViewPatchOp.set('status', {'value': 'Greeted \$greetings time(s)'}),
      ]));
    }

    context.registerMenuItem(
      'Tools/$friendly/Say Hello',
      PluginProcessCommand(id: '$pluginName.hello', label: 'Say Hello', run: greet),
    );
    context.registerViewPanel(PluginProcessViewPanel(
      id: '$pluginName.panel',
      title: '$friendly',
      dock: 'right',
      initial: PluginViewSpec(id: '$pluginName.view', children: [
        PluginControl.text('status', 'Ready'),
        PluginControl.button('hello', 'Say Hello', tone: 'primary'),
      ]),
      onEvent: (event, view) async {
        if (event.controlId == 'hello' && event.kind == 'pressed') await greet();
      },
    ));
    context.registerMcpTool(McpTool(
      name: '${pluginName}_greetings',
      description: 'How many times $friendly said hello.',
      inputSchema: McpSchema.object({}),
      handler: (_) => McpToolResult.json({'greetings': greetings}),
      risk: McpToolRisk.readOnly,
      groups: {McpToolGroups.plugin},
    ));
  }
}
''';
  }

  /// `test/<name>_process_test.dart`: against the pure-Dart loopback host.
  static String processTest({required String pluginName, required String pascalName}) => '''// Shipped test for the $pascalName process
import 'package:lumina_plugin_process/lumina_plugin_process.dart';
import 'package:lumina_plugin_process/testing.dart';
import 'package:test/test.dart';
import 'package:$pluginName/$pluginName.dart';

void main() {
  test('$pascalName registers its menu item, panel and MCP tool; the command asks before it acts', () async {
    final host = await LoopbackHost.start();
    addTearDown(host.close);
    host.answerDialog = (spec) => const PluginDialogResult(action: 'confirm');
    final exit = runPluginProcessMain(host.launch('$pluginName'), ${pascalName}Process());
    final contributions = await host.contributions;
    expect(contributions.menuItems.single.command.id, '$pluginName.hello');
    expect(contributions.panels.single.id, '$pluginName.panel');
    expect(contributions.mcpTools.single.name, '${pluginName}_greetings');

    await host.call(PluginMethods.command, {'commandId': '$pluginName.hello'});
    final log = await host.next(PluginMethods.log, where: (a) => '\${a['message']}'.contains('Hello'));
    expect(log['message'], contains('(1)'));

    await host.call(PluginMethods.shutdown);
    expect(await exit, PluginProcessExitCodes.ok);
  });
}
''';

  /// `test/architecture/process_entry_reach_test.dart`: the entry reaches
  /// no Flutter.
  static String reachTest({required String pluginName}) => '''// Shipped test: a kernel plugin's process runs on the plain Dart VM
import 'dart:io';

import 'package:lumina_plugin_process/testing.dart';
import 'package:test/test.dart';

void main() {
  test('the process entry reaches no Flutter or dart:ui', () {
    final reach = PluginProcessReach.ofEntry(File('bin/${pluginName}_process.dart'), pluginDir: Directory.current);
    expect(reach.flutterPackages, isEmpty, reason: reach.describeFlutter());
  });
}
''';

  /// The README section a kernel plugin adds.
  static String readme({required String pluginName, required String pascalName}) => '''
(kernel plugin: runs on the Dart VM, no editor rebuild)

## A kernel plugin
- `bin/${pluginName}_process.dart` is the process entry (the manifest's
  `process_entry`); `lib/src/${pluginName}_process.dart` (`${pascalName}Process`,
  the `process_class`) registers a menu command, a declarative panel and an
  MCP tool. There is no `registration_class`: nothing of the plugin is
  compiled into the editor, so enabling, disabling or updating it takes
  effect at once, without a project editor build or restart.
- Keep it pure Dart: the entry may not import Flutter or `dart:ui`
  (`test/architecture/process_entry_reach_test.dart`).
- `dart run tool/pack_plugin.dart` compiles the kernel
  (`bin/${pluginName}_process.dill` plus its `.sha256`) and stamps the Dart SDK
  that built it (`process_kernel_sdk`). An editor on another Dart SDK
  recompiles it from the packed source once and caches it.''';
}
