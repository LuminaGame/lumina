// Compiles the OpenDLSS-NR compute kernels (the vendored GLSL route in
// third_party/opendlss_nr/upstream/shaders and Lumina's frame passes in
// src/opendlss_nr/shaders) to SPIR-V and writes them as C arrays into
// src/opendlss_nr/spirv.h:
//
//   dart tool/build_opendlss_nr_shaders.dart   (plain dart: no build hooks needed)
//
// Needs glslang 16.6 or newer (`glslangValidator`, the Vulkan SDK's, or
// VULKAN_SDK/Bin on Windows): the kernels use GL_EXT_float_e4m3 and
// GL_NV_cooperative_matrix2, which need SPIR-V 1.6 (--target-env vulkan1.3).
// The generated header is committed, so a normal build needs no compiler.
import 'dart:io';

const _upstream = 'third_party/opendlss_nr/upstream/shaders';
const _lumina = 'src/opendlss_nr/shaders';
const _out = 'src/opendlss_nr/spirv.h';

/// Module name -> source. The names are the ones the kernels ask for.
const shaders = {
  'gemm_fp8': '$_upstream/gemm_fp8.comp',
  'gemm_f16': '$_upstream/gemm_f16.comp',
  'gemm_mlp': '$_upstream/gemm_mlp.comp',
  'gemm_reduce': '$_upstream/gemm_reduce.comp',
  'ops': '$_upstream/ops.comp',
  'window_normalize': '$_upstream/window_normalize.comp',
  'window_attend': '$_upstream/window_attend.comp',
  'global_normalize': '$_upstream/global_normalize.comp',
  'global_attend': '$_upstream/global_attend.comp',
  'global_attention': '$_upstream/global_attention.comp',
  'fused_block32': '$_upstream/fused_block32.comp',
  'qkv_attention': '$_upstream/qkv_attention.comp',
  'nr_features': '$_lumina/nr_features.comp',
  'nr_composite': '$_lumina/nr_composite.comp',
};

Future<void> main(List<String> args) async {
  final glslang = _findGlslang();
  final tmp = await Directory.systemTemp.createTemp('opendlss_nr_spv');
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/build_opendlss_nr_shaders.dart — do not edit.')
    ..writeln('// SPIR-V of the OpenDLSS-NR GLSL kernels (third_party/opendlss_nr, MIT) and Lumina\'s frame passes.')
    ..writeln('#pragma once')
    ..writeln('#include <stdint.h>')
    ..writeln('#include <string.h>')
    ..writeln()
    ..writeln('namespace opendlss_nr {')
    ..writeln();
  final table = <String>[];
  try {
    for (final entry in shaders.entries) {
      final source = entry.value;
      final spv = File('${tmp.path}/${entry.key}.spv');
      final result = await Process.run(glslang, [
        '-V',
        '--target-env',
        'vulkan1.3',
        '-I${File(source).parent.path}',
        source,
        '-o',
        spv.path,
      ]);
      if (result.exitCode != 0) {
        stderr
          ..write(result.stdout)
          ..write(result.stderr);
        exitCode = 1;
        return;
      }
      final bytes = await spv.readAsBytes();
      final words = <String>[];
      for (var i = 0; i + 3 < bytes.length; i += 4) {
        final w = bytes[i] | (bytes[i + 1] << 8) | (bytes[i + 2] << 16) | (bytes[i + 3] << 24);
        words.add('0x${w.toRadixString(16).padLeft(8, '0')}u');
      }
      final symbol = 'kSpirv_${entry.key}';
      out.writeln('// $source');
      out.writeln('static const uint32_t $symbol[] = {');
      for (var i = 0; i < words.length; i += 8) {
        out.writeln('    ${words.sublist(i, i + 8 > words.length ? words.length : i + 8).join(', ')},');
      }
      out.writeln('};');
      out.writeln();
      table.add('    {"${entry.key}", $symbol, ${words.length}},');
      stdout.writeln('$source -> ${entry.key} (${bytes.length} bytes)');
    }
  } finally {
    await tmp.delete(recursive: true);
  }
  out
    ..writeln('struct SpirvModule {')
    ..writeln('  const char* name;')
    ..writeln('  const uint32_t* code;')
    ..writeln('  size_t words;')
    ..writeln('};')
    ..writeln()
    ..writeln('static const SpirvModule kSpirvModules[] = {')
    ..writeAll(table, '\n')
    ..writeln()
    ..writeln('};')
    ..writeln()
    ..writeln('inline const SpirvModule* findSpirv(const char* name) {')
    ..writeln('  for (const SpirvModule& m : kSpirvModules) {')
    ..writeln('    if (strcmp(m.name, name) == 0) return &m;')
    ..writeln('  }')
    ..writeln('  return nullptr;')
    ..writeln('}')
    ..writeln()
    ..writeln('}  // namespace opendlss_nr');
  await File(_out).writeAsString(out.toString());
  stdout.writeln('wrote $_out');
}

String _findGlslang() {
  final sdk = Platform.environment['VULKAN_SDK'];
  if (sdk != null) {
    final candidate = File('$sdk/${Platform.isWindows ? 'Bin/glslangValidator.exe' : 'bin/glslangValidator'}');
    if (candidate.existsSync()) return candidate.path;
  }
  return 'glslangValidator';
}
